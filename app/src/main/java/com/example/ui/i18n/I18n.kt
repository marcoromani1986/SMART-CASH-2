    fun t(key: String, lang: String, vars: Map<String, String> = emptyMap()): String {
        val dict = when (lang) {
            "it" -> it
            "ar" -> ar
            else -> en
        }
        var res = dict[key] ?: en[key] ?: key
        for ((k, v) in vars) {
            res = res.replace("{$k}", v)
        }
        return res
    }

    fun fmtNum(num: Double): String {
        val symbols = DecimalFormatSymbols(Locale.US)
        val df = DecimalFormat("#,##0.00", symbols)
        return df.format(num)
    }

    fun fmtAmount(num: Double, currency: String): String {
        val sym = CURRENCY_SYMBOLS[currency] ?: currency
        val sign = if (num < 0) "-" else ""
        return "$sym $sign${fmtNum(kotlin.math.abs(num))}"
    }

    fun fmtDateShort(iso: String): String {
        return try {
            val inSdf = SimpleDateFormat("yyyy-MM-dd", Locale.US)
            val d = inSdf.parse(iso) ?: return iso
            val outSdf = SimpleDateFormat("d MMM", Locale.US)
            outSdf.format(d)
        } catch (e: Exception) {
            iso
        }
    }
